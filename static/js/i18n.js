export const LANGS = ['en', 'de'];

function initialLang() {
  try {
    const saved = localStorage.getItem('wargame.lang');
    if (saved === 'en' || saved === 'de') return saved;
  } catch { /* storage blocked */ }
  return (navigator.language || 'en').toLowerCase().startsWith('de') ? 'de' : 'en';
}

let lang = initialLang();
const listeners = new Set();

export function getLang() { return lang; }

export function setLang(l) {
  if (!LANGS.includes(l) || l === lang) return;
  lang = l;
  try { localStorage.setItem('wargame.lang', l); } catch { /* ignore */ }
  for (const fn of listeners) fn(l);
}

export function onLangChange(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

// UI string. vars replace {name} placeholders.
export function t(key, vars = null, l = lang) {
  let s = STRINGS[l]?.[key] ?? STRINGS.en[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined && vars[k] !== null ? String(vars[k]) : m));
  return s;
}

// Bilingual content value {en, de} -> string, falling back to the other language.
export function tr(v, l = lang) {
  if (v == null) return '';
  if (typeof v === 'string') return v;
  return v[l] || v[l === 'en' ? 'de' : 'en'] || '';
}
